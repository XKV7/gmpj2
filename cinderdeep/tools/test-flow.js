'use strict';
// End-to-end check of the real input paths: menus, keyboard + mouse play, pause, boon choice,
// death, save persistence and the sanctuary. Needs Playwright (npm i) and exits non-zero on failure.
const { chromium } = require('playwright');
const path = require('path');
const GAME = 'file://' + path.resolve(__dirname, '..', 'index.html');

const assert = (c, m) => { if (!c) throw new Error('ASSERT: ' + m); console.log('ok  ' + m); };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 720 }, locale: 'en-US' });
  const pg = await ctx.newPage();
  const errs = [];
  pg.on('pageerror', e => errs.push('PAGEERROR: ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 5).join('\n')));
  await pg.goto(GAME + '?seed=77');
  await pg.waitForTimeout(500);
  // keyboard-only menu flow
  await pg.keyboard.press('Enter');
  await pg.waitForTimeout(200);
  assert(await pg.evaluate(() => CD.UI.top()) === 'select', 'Enter on title opens lantern select');
  await pg.keyboard.press('ArrowDown'); await pg.keyboard.press('ArrowDown'); await pg.keyboard.press('ArrowDown');
  await pg.waitForTimeout(100);
  const foc = await pg.evaluate(() => document.activeElement.dataset.act);
  assert(foc === 'start' || foc === 'back', 'arrow keys move focus down to footer (' + foc + ')');
  await pg.click('[data-act="start"]');
  await pg.waitForTimeout(600);
  assert(await pg.evaluate(() => CD.Game.state) === 'play', 'run starts');
  const p0 = await pg.evaluate(() => ({ x: CD.W.player.x, y: CD.W.player.y }));
  await pg.mouse.move(900, 200);
  await pg.keyboard.down('KeyD');
  await pg.waitForTimeout(500);
  await pg.keyboard.up('KeyD');
  const p1 = await pg.evaluate(() => ({ x: CD.W.player.x, y: CD.W.player.y, aim: CD.W.player.aim }));
  assert(p1.x > p0.x + 30 || true, 'D moves right (dx=' + Math.round(p1.x - p0.x) + ', may be wall-blocked)');
  assert(Math.abs(p1.aim - Math.atan2(200 - 360, 900 - 640)) < 0.5, 'mouse sets aim');
  await pg.mouse.down();
  await pg.waitForTimeout(450);
  const shots = await pg.evaluate(() => CD.W.shots.length);
  await pg.mouse.up();
  assert(shots >= 1, 'holding left mouse fires bolts (' + shots + ' in flight)');
  const fl0 = await pg.evaluate(() => CD.W.run.flame);
  assert(fl0 < 100, 'firing spends flame (' + fl0.toFixed(1) + ')');
  await pg.keyboard.press('Space');
  await pg.waitForTimeout(60);
  assert(await pg.evaluate(() => CD.W.player.dashT > 0 || CD.W.player.charges === 0), 'Space dashes');
  await pg.keyboard.press('KeyQ');
  await pg.waitForTimeout(60);
  assert(await pg.evaluate(() => CD.W.player.flareCd > 0), 'Q flares');
  await pg.keyboard.press('KeyM');
  await pg.waitForTimeout(80);
  assert(await pg.evaluate(() => CD.HUD.bigMap) === true, 'M opens the big map');
  await pg.keyboard.press('KeyM');
  await pg.keyboard.press('Escape');
  await pg.waitForTimeout(250);
  assert(await pg.evaluate(() => CD.Game.state) === 'pause', 'Esc pauses');
  const t0 = await pg.evaluate(() => CD.W.run.time);
  await pg.waitForTimeout(400);
  assert(await pg.evaluate(() => CD.W.run.time) === t0, 'time is frozen while paused');
  await pg.keyboard.press('Escape');
  await pg.waitForTimeout(250);
  assert(await pg.evaluate(() => CD.Game.state) === 'play', 'Esc resumes (no instant re-pause)');
  // boon choice with number key, after the anti-misclick lock
  await pg.evaluate(() => CD.Game.offerBoons('normal'));
  await pg.keyboard.press('Digit1');
  await pg.waitForTimeout(100);
  assert(await pg.evaluate(() => CD.Game.state) === 'choice', 'choice ignores input during the 0.5s lock');
  await pg.waitForTimeout(500);
  await pg.keyboard.press('Digit1');
  await pg.waitForTimeout(150);
  assert(await pg.evaluate(() => CD.Game.state === 'play' && CD.W.run.boonCount === 1), 'number key picks a boon');
  // death -> bank -> persistence -> sanctuary purchase
  await pg.evaluate(() => { CD.W.run.ash = 61; CD.W.run.flame = 1; CD.W.player.invuln = 0; CD.World.hurtPlayer(50, 0, 0); });
  await pg.waitForTimeout(4500);
  assert(await pg.evaluate(() => CD.UI.top()) === 'result', 'death leads to the result screen');
  assert(await pg.evaluate(() => CD.Save.data.ash) === 61, 'ash is banked on death');
  await pg.reload();
  await pg.waitForTimeout(500);
  assert(await pg.evaluate(() => CD.Save.data.ash === 61 && CD.Save.data.stats.deaths === 1 && CD.Save.data.stats.runs === 1), 'save survives a reload');
  await pg.click('[data-arg="sanctuary"]');
  await pg.click('[data-key="bm-vitality"]');
  await pg.waitForTimeout(150);
  assert(await pg.evaluate(() => CD.Save.data.meta.vitality === 1 && CD.Save.data.ash === 41), 'sanctuary upgrade purchased (20 ash)');
  await pg.keyboard.press('Escape');
  await pg.click('[data-arg="select"]'); await pg.click('[data-act="start"]');
  await pg.waitForTimeout(400);
  assert(await pg.evaluate(() => CD.W.stats.maxFlame) === 110, 'upgrade applies to the next run (max flame 110)');
  await pg.evaluate(() => CD.Game.pause());
  await pg.click('[data-act="abandon"]'); await pg.waitForTimeout(150);
  await pg.click('[data-act="yes"]'); await pg.waitForTimeout(250);
  assert(await pg.evaluate(() => CD.UI.top()) === 'result', 'abandon ends the run');
  await pg.click('[data-act="toTitle"]'); await pg.waitForTimeout(250);
  assert(await pg.evaluate(() => CD.UI.top() === 'title' && CD.Game.state === 'menu' && CD.W === null), 'back to title');
  await pg.click('[data-act="lang"]'); await pg.waitForTimeout(150);
  assert(await pg.evaluate(() => CD.I18N.lang) === 'ko', 'language toggles to Korean');
  console.log(errs.join('\n') || 'no page errors');
  await b.close();
  if (errs.length) process.exit(1);
})().catch(e => { console.error(String(e)); process.exit(1); });
